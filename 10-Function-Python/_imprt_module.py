def tambah (a, b) :
    return a + b

def kurang (a, b) :
    return a - b 

def kali (a, b) :
    return a * b

def bagi (a, b) :
    return a / b

def pangkat (a, b) :
    return a ** b

def keliling_lingkaran (r) :
    hasil = 2 * 3.14 * r
    return hasil


def hallo (nama) :
    print(f"Hallo {nama}")

def hallo_dua (nama, umur) :
    print(f"Hallo {nama} Umur kamu : {umur}")

def hallo_tiga (nama, umur=0) :
    print(f"Hallo {nama} Umur kamu : {umur}")


