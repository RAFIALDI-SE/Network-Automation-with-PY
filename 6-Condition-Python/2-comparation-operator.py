# Belajar komparasion operator untuk percabangan
# == ini perbandingan jika nilai sama maka hasilnya akan true
# != ini perbandingan tidak sama dengan, jika ke dua nilai beda maka true
# > ini lebih dari
# < ini kurang dari
# >= ini lebih dari sama dengan
# <= ini kurang dari sama dengan
# % ini hasil bagi atau modulus

a = 10
b = 5

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
print(a % b)